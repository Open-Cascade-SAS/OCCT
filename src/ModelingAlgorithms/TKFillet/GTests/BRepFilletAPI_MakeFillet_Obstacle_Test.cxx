TEST(BRepFilletAPI_MakeFilletTest, OCCT1568_BlendEndingAtRoundVertexDoesNotCrash)
{
  std::istringstream aStream(brepWindow());
  TopoDS_Shape       aShape;
  BRep_Builder       aBuilder;
  BRepTools::Read(aShape, aStream, aBuilder);
  ASSERT_FALSE(aShape.IsNull());

  // The edge of the top plane (z = 20) on the plane y = 88.097: a straight rim edge of the pocket.
  TopoDS_Edge aRimEdge;
  for (TopExp_Explorer anExp(aShape, TopAbs_EDGE); anExp.More(); anExp.Next())
  {
    const TopoDS_Edge& anEdge = TopoDS::Edge(anExp.Current());
    BRepAdaptor_Curve  aCurve(anEdge);
    if (aCurve.GetType() != GeomAbs_Line)
    {
      continue;
    }
    const gp_Pnt aFirst = aCurve.Value(aCurve.FirstParameter());
    const gp_Pnt aLast  = aCurve.Value(aCurve.LastParameter());
    if (std::abs(aFirst.Z() - 20.0) < 1.e-6 && std::abs(aLast.Z() - 20.0) < 1.e-6
        && std::abs(aFirst.Y() - 88.097) < 1.e-3 && std::abs(aLast.Y() - 88.097) < 1.e-3)
    {
      aRimEdge = anEdge;
      break;
    }
  }
  ASSERT_FALSE(aRimEdge.IsNull());

  // The parameters of the DRAW command "blend" (BRepTest_FilletCommands.cxx), with which the
  // issue was reported: the crash does not occur with the default tolerances.
  BRepFilletAPI_MakeFillet aFillet(aShape, ChFi3d_Rational);
  aFillet.SetParams(1.e-2, 1.e-4, 1.e-5, 1.e-4, 1.e-5, 1.e-3);
  aFillet.SetContinuity(GeomAbs_C1, 1.e-2);
  aFillet.Add(1.5, aRimEdge);

  // Used to terminate the process with SIGSEGV inside Build().
  aFillet.Build();

  // The blend is not expected to be built here (as for the radius of 1.4999999), but only that
  // Build() returns is checked; a result, if there is one, must be a shape.
  if (aFillet.IsDone())
  {
    EXPECT_FALSE(aFillet.Shape().IsNull());
  }
}
